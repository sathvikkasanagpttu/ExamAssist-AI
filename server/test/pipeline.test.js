test("Source Deduplication eliminates duplicate URLs and titles", () => {
  const mockSources = [
    { title: "Mitochondria Overview", url: "https://en.wikipedia.org/wiki/Mitochondria?utm_source=test", snippet: "Powerhouse of the cell." },
    { title: "Mitochondria Overview", url: "https://en.wikipedia.org/wiki/Mitochondria#history", snippet: "Organelle inside eukaryotes." },
    { title: "NCBI Cellular Respiration", url: "https://ncbi.nlm.nih.gov/books/NBK12345/", snippet: "ATP generation occurs in inner membrane." }
  ];

  const deduped = deduplicateSources(mockSources);
  assert.equal(deduped.length, 2, "Should deduplicate normalized URLs/titles");
  assert.equal(deduped[0].url, "https://en.wikipedia.org/wiki/Mitochondria");
});

test("Source Evaluator scores institutional and reference domains", async () => {
  const analysis = analyzeQuestion("Mitochondria function ATP");
  const sources = [
    { title: "NIH Mitochondria", url: "https://ncbi.nlm.nih.gov/cell", domain: "ncbi.nlm.nih.gov", snippet: "Mitochondria generate ATP." },
    { title: "Random Blog", url: "https://myblog.com/cells", domain: "myblog.com", snippet: "Cells are cool." }
  ];

  const evaluated = await evaluateSources(sources, analysis);
  assert.equal(evaluated.length, 2);
  assert.ok(evaluated[0].authority_score > evaluated[1].authority_score, "Institutional source should have higher authority");
  assert.equal(evaluated[0].quality, "HIGH");
});

test("Verifier detects source agreement and claim support", async () => {
  const sources = [
    { title: "Doc 1", url: "https://nih.gov", quality: "HIGH", snippet: "ATP is generated by ATP synthase in mitochondria." },
    { title: "Doc 2", url: "https://stanford.edu", quality: "HIGH", snippet: "Mitochondrial matrix and cristae synthesize ATP." }
  ];

  const contradictions = await detectContradictions("How do mitochondria make ATP?", sources);
  assert.equal(contradictions.status, "AGREEMENT");

  const verification = await verifyEvidence("How do mitochondria make ATP?", "Mitochondria synthesize ATP.", sources, contradictions);
  assert.equal(verification.overall_evidence_level, "HIGH");
  assert.ok(verification.claims.length > 0);
});

