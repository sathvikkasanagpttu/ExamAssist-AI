test("Verifier assigns CONFLICTING when sources genuinely disagree", async () => {
  const conflictingSources = [
    { title: "Study A", url: "https://journal-a.org", quality: "HIGH", snippet: "Method X yields positive outcomes under all conditions." },
    { title: "Study B", url: "https://journal-b.org", quality: "HIGH", snippet: "Method X fails to produce positive outcomes in replicated trials." }
  ];

  const contradictionResult = {
    status: "CONFLICTING_EVIDENCE",
    agreement: [],
    conflicts: [{ claim: "Efficacy of Method X", source_a: 1, source_b: 2, discrepancy: "Contradictory clinical outcomes" }],
    explanation: "Replication studies disagree on the efficacy."
  };

  const verification = await verifyEvidence(
    "Is Method X effective?",
    "Method X is universally effective.",
    conflictingSources,
    contradictionResult
  );

  assert.equal(verification.overall_evidence_level, "CONFLICTING");
});

test("Verifier assigns UNVERIFIED when no sources are available", async () => {
  const contradictionResult = { status: "AGREEMENT", agreement: [], conflicts: [], explanation: "" };
  const verification = await verifyEvidence("Obscure unindexed question?", "Unverified answer.", [], contradictionResult);
  assert.equal(verification.overall_evidence_level, "UNVERIFIED");
});

