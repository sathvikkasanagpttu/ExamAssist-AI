test("Question Analyzer identifies MCQ questions", () => {
  const mcq = `What is the primary function of mitochondria?
A) Protein synthesis
B) ATP generation through cellular respiration
C) Lipid storage
D) DNA replication`;

  const analysis = analyzeQuestion(mcq);
  assert.equal(analysis.isMCQ, true);
  assert.equal(analysis.category, "multiple_choice");
  assert.equal(analysis.subject, "Biology");
  assert.equal(analysis.options.length, 4);
  assert.ok(analysis.options[1].includes("ATP generation"));
});

